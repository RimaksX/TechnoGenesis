def valve(m, x, y, z, dx=2, dz=2):
    """Вентиль на трубе: стойка и медный маховик сверху."""
    m.box([x + dx // 2 - (1 if dx > 1 else 0), y, z + dz // 2 - (1 if dz > 1 else 0)],
          [x + dx // 2 + (0 if dx > 1 else 1), y + 1, z + dz // 2 + (0 if dz > 1 else 1)], "dark")
    m.box([x, y + 1, z], [x + dx, y + 2, z + dz], "copper")


def vent(m, x0, y0, z0, x1, y1, z1, faces="n"):
    """Вентиляционная решётка: у детали решёткой нарисованы указанные грани."""
    mats = {f: "grate" for f in faces}
    mats["*"] = "dark"
