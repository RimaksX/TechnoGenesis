def _with_wires(name, fn):
    def build():
        from .fill import fill_floor
        m = fn()
        X, Y, Z, xm = m.X, m.Y, m.Z, m.xm
        if name == "solar_farm":
            route_wires(m, (X, Y, Z), [(rgb, a, b) for rgb, a, b in WIRING[name]])
            return m
        reserve = [((2, 2, 3), (7, Y, 13)), ((X - 7, 2, 3), (X - 2, Y, 13)), ((xm + 3, 2, Z - 7), (xm + 13, Y, Z - 2)),
                   ((xm + 3, 2, 2), (xm + 13, Y, 7)), ((xm + 3, 2, Z - 14), (xm + 13, Y, Z - 3))]
        from .fill import Grid, occupancy, add_decks
        grid = Grid(occupancy(m, (X, Y, Z)))
        acc = ACCENT.get(name, (110, 114, 120))
        placed = fill_floor(m, (X, Y, Z), xm, acc, _unit_mats(), reserve, grid=grid)
        for k in range(1, m.h):                                              # настил и узлы на верхних ярусах
            level = 16 * k
            if add_decks(m, (X, Y, Z), grid, level, {"u": "grate", "*": "dark"}):
                placed += fill_floor(m, (X, Y, Z), xm, acc, _unit_mats(), [], floor=level + 1, maxunits=6, target=0.6,
                                     grid=grid)
        cab_i = next((i for i, (n, _) in enumerate(placed) if n.startswith("cabinet")), None)
        if cab_i is not None and cab_i != 0:
            placed.insert(0, placed.pop(cab_i))
        hub = placed[0][1] if placed and placed[0][0].startswith("cabinet") else None
        sockets = {"R": (1, 11, 8), "L": (X - 2, 11, 8), "B": (xm + 8, 11, Z - 1), "F": (xm + 8, 11, 1),
                   "T": (xm + 8, Y - 3, Z - 8), "D": (xm + 8, 2, Z - 8), "LAMP": (xm + 8, 3, 2)}
        specs = []
        for rgb, a, b in WIRING.get(name, []):
            if isinstance(a, str) and a != "LAMP" and rgb == RED and hub:
                specs.append((RED, hub, b))                              # силовой провод от щита питания к двигателю или шине
            else:
                specs.append((rgb, sockets[a] if isinstance(a, str) else a, b))
        if hub:
            specs.append((BLUE, sockets["LAMP"], hub))                    # панель индикаторов связана со щитом
            for key in ("R", "L", "B", "F", "T", "D"):                    # от каждого гнезда - провод к щиту питания
                specs.append((RED, sockets[key], hub))
            for (n, c) in placed[1:]:
                if n in ("pump", "cabinet", "cabinet_small"):
                    specs.append((RED, hub, c))
        route_wires(m, (X, Y, Z), specs)
        return m
    build.__name__ = name
    return build


