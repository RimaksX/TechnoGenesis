class Big(Model):
    def __init__(self, mid, w, d, h):
        super().__init__(mid)
        self.w, self.d, self.h = w, d, h
        self.X, self.Z, self.Y = 16 * w, 16 * d, 16 * h
        self.xm = 16 * ((w - 1) // 2)          # левый край центрального столбца: сюда выведены разъёмы зад/верх/низ

    def parts(self):
        return self.w * self.d * self.h


def gaps(lo, hi, blocked):
    """Отрезки [lo, hi] за вычетом занятых интервалов."""
    out, cur = [], lo
    for a, b in sorted(blocked):
        if a > cur:
            out.append((cur, a))
        cur = max(cur, b)
    if cur < hi:
        out.append((cur, hi))
    return out


def port_mat(base="light"):
    return ("port", (base,))


def chassis(m, tint=None, sockets=True):
    """Рама всей машины: основание-плита с гнездом снизу, рёбра, стойки по углам и на стыках клеток, пояса между слоями,
    полки под боковыми гнёздами, три боковых гнезда и верхнее гнездо на перемычке."""
    fr = "casing"                                                            # рама всегда тёмно-серая; красить можно только начинку
    X, Z, Y, xm = m.X, m.Z, m.Y, m.xm
    seam_x = [16 * k for k in range(1, m.w)]
    seam_z = [16 * k for k in range(1, m.d)]
    seam_y = [16 * k for k in range(1, m.h)]
    # нижние и верхние рёбра по периметру
    m.box([0, 0, 0], [X, 2, 2], fr)                                         # лицевое нижнее ребро
    m.box([0, Y - 2, 0], [xm + 4, Y, 2], fr)                                # лицевое верхнее ребро с гнездом под индикатор
    m.box([xm + 4, Y - 2, 0], [xm + 12, Y, 2], "dark")
    m.box([xm + 12, Y - 2, 0], [X, Y, 2], fr)
    for y0 in (0, Y - 2):
        m.box([0, y0, Z - 2], [X, y0 + 2, Z], fr)
        m.box([0, y0, 2], [2, y0 + 2, Z - 2], fr)
        m.box([X - 2, y0, 2], [X, y0 + 2, Z - 2], fr)
    # основание: плита с вырезом под нижнее гнездо
    sx0, sx1, sz0, sz1 = xm + 5, xm + 11, Z - 11, Z - 5
    if sockets:
        m.box([2, 0, 2], [sx0, 2, Z - 2], "dark")
        m.box([sx1, 0, 2], [X - 2, 2, Z - 2], "dark")
        m.box([sx0, 0, 2], [sx1, 2, sz0], "dark")
        m.box([sx0, 0, sz1], [sx1, 2, Z - 2], "dark")
        m.box([sx0, 0, sz0], [sx1, 2, sz1], {"d": port_mat(), "*": "light"})
    else:
        m.box([2, 0, 2], [X - 2, 2, Z - 2], "dark")
    # стойки: углы и стыки клеток по лицевой/задней стенкам, стыки по боковым
    post_x = [0] + [s - 1 for s in seam_x] + [X - 2]
    post_z = [s - 1 for s in seam_z]
    ysegs, prev = [], 2
    for s in seam_y:
        ysegs.append((prev, s - 1))
        prev = s + 1
    ysegs.append((prev, Y - 2))
    for (y0, y1) in ysegs:
        for px in post_x:
            m.box([px, y0, 0], [px + 2, y1, 2], fr)
            m.box([px, y0, Z - 2], [px + 2, y1, Z], fr)
        for pz in post_z:
            m.box([0, y0, pz], [2, y1, pz + 2], fr)
            m.box([X - 2, y0, pz], [X, y1, pz + 2], fr)
    # пояса между слоями
    zb = [(pz, pz + 2) for pz in post_z]
    for s in seam_y:
        m.box([0, s - 1, 0], [X, s + 1, 2], fr)
        m.box([0, s - 1, Z - 2], [X, s + 1, Z], fr)
        m.box([0, s - 1, 2], [2, s + 1, Z - 2], fr)
        m.box([X - 2, s - 1, 2], [X, s + 1, Z - 2], fr)
    # полки под боковыми гнёздами (нижний слой)
    for (a, b) in gaps(2, Z - 2, zb):
        m.box([0, 3, a], [2, 5, b], fr)
        m.box([X - 2, 3, a], [X, 5, b], fr)
    for (a, b) in gaps(2, X - 2, [(px, px + 2) for px in post_x[1:-1]]):
        m.box([a, 3, Z - 2], [b, 5, Z], fr)
    # поперечины крыши по стыкам клеток (угловых кубиков-косынок нет)
    zb2 = [(16 * j - 1, 16 * j + 1) for j in range(1, m.d)]
    xb2 = [(16 * k - 1, 16 * k + 1) for k in range(1, m.w)]
    for (a, b) in xb2:
        m.box([a, Y - 2, 2], [b, Y, Z - 2], fr)
    for (a, b) in zb2:
        for (c, d) in gaps(2, X - 2, xb2):
            m.box([c, Y - 2, a], [d, Y, b], fr)
    # передний ряд: полка под гнездом, панель индикаторов и переднее гнездо
    lp0, lp1 = xm + 4, xm + 12
    for (a, b) in gaps(2, X - 2, [(px, px + 2) for px in post_x] + [(lp0, lp1)]):
        m.box([a, 2, 0], [b, 5, 2], fr)
    m.box([lp0, 2, 0], [lp1, 5, 2], {"n": console_mat(MM.GL, None), "*": "dark"})
    if not sockets:
        return
    m.box([xm + 5, 5, 0], [xm + 11, 11, 2], {"n": port_mat(), "*": "light"})
    # гнёзда
    m.box([0, 5, 5], [2, 11, 11], {"w": port_mat(), "*": "light"})
    m.box([X - 2, 5, 5], [X, 11, 11], {"e": port_mat(), "*": "light"})
    m.box([xm + 5, 5, Z - 2], [xm + 11, 11, Z], {"s": port_mat(), "*": "light"})
    m.box([xm + 5, Y - 2, Z - 11], [xm + 11, Y, Z - 5], {"u": port_mat(), "*": "light"})
    m.box([xm + 7, Y - 2, Z - 5], [xm + 9, Y, Z - 2], fr)                    # перемычка к заднему ребру


