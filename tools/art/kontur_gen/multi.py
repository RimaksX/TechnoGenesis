def band_sides(m, x0, z0, x1, z1, y, sides="lbr", mat="dark"):
    """Бандаж только с выбранных сторон: l - слева (x0), r - справа (x1), b - сзади (z1), f - спереди (z0)."""
    if "b" in sides:
        m.box([x0 - 1 if "l" in sides else x0, y, z1], [x1 + 1 if "r" in sides else x1, y + 1, z1 + 1], mat)
    if "f" in sides:
        m.box([x0 - 1 if "l" in sides else x0, y, z0 - 1], [x1 + 1 if "r" in sides else x1, y + 1, z0], mat)
    if "l" in sides:
        m.box([x0 - 1, y, z0], [x0, y + 1, z1], mat)
    if "r" in sides:
        m.box([x1, y, z0], [x1 + 1, y + 1, z1], mat)


