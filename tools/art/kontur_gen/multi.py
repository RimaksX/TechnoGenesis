def _crop(inner, ox, oy, fw, fh, seed):
    return lambda frame: ("crop", (inner, ox, oy, fw, fh, seed))


def _offsets(f, bx, a, b):
    """Смещение куска грани внутри целой грани (в пикселях): (ox, oy)."""
    if f == "north":
        return bx.b[0] - b[0], bx.b[1] - b[1]
    if f == "south":
        return a[0] - bx.a[0], bx.b[1] - b[1]
    if f == "east":
        return bx.b[2] - b[2], bx.b[1] - b[1]
    if f == "west":
        return a[2] - bx.a[2], bx.b[1] - b[1]
    if f == "up":
        return a[0] - bx.a[0], a[2] - bx.a[2]
    return a[0] - bx.a[0], bx.b[2] - b[2]                  # down


def slice_model(big):
    """Режет модель на клетки. Возвращает {номер части: Model}; грани на плоскостях разреза отбрасываются."""
    cull_hidden_faces(big)
    parts = {}
    for c, r, y in product(range(big.w), range(big.d), range(big.h)):
        idx = y * big.w * big.d + r * big.w + c
        lo = (16 * c, 16 * y, 16 * r)
        pm = Model(f"{big.id}_p{idx}")
        pm.seed = (big.seed + idx * 13) % 1000
        for bi, bx in enumerate(big.boxes):
            if bx.rot:
                raise ValueError(f"{big.id}: повёрнутые детали в крупной модели не поддерживаются ({bx.name})")
            a = [max(bx.a[i], lo[i]) for i in range(3)]
            b = [min(bx.b[i], lo[i] + 16) for i in range(3)]
            if any(b[i] - a[i] <= EPS for i in range(3)):
                continue
            whole = all(abs(a[i] - bx.a[i]) < EPS and abs(b[i] - bx.b[i]) < EPS for i in range(3))
            faces, mats = [], {}
            for f in bx.faces:
                ax, sg = NORMAL[f]
                kept = abs(b[ax] - bx.b[ax]) < EPS if sg > 0 else abs(a[ax] - bx.a[ax]) < EPS
                if not kept:
                    continue
                faces.append(f)
                if whole:
                    mats[f] = bx.mat[f]
                else:
                    fw, fh = (int(round(v)) for v in face_dims(bx, f))
                    ox, oy = _offsets(f, bx, a, b)
                    mats[f] = _crop(bx.mat[f], int(round(ox)), int(round(oy)), fw, fh, big.seed + bi * 7 + len(f))
            if faces:
                pm.boxes.append(Box([a[i] - lo[i] for i in range(3)], [b[i] - lo[i] for i in range(3)], mats, faces,
                                    None, bx.name))
        parts[idx] = pm
    return parts


def check_big(big):
    """Проверки крупной модели: целые координаты в габаритах, отсутствие пересечений объёмов и z-fighting."""
    from .model3d import volume_overlaps, floating, _plane, _rect
    issues = []
    for bx in big.boxes:
        if min(bx.a) < 0 or bx.b[0] > big.X or bx.b[1] > big.Y or bx.b[2] > big.Z:
            issues.append(f"габариты: {bx.name} {bx.a}-{bx.b}")
        for v in list(bx.a) + list(bx.b):
            if abs(v - round(v)) > 1e-6:
                issues.append(f"сетка: {bx.name} {v}")
                break
        if any(bx.b[i] - bx.a[i] <= 0 for i in range(3)):
            issues.append(f"пустая деталь: {bx.name} {bx.a}-{bx.b}")
    bs = big.boxes
    for i in range(len(bs)):
        for j in range(i + 1, len(bs)):
            for f in bs[i].faces:
                if f not in bs[j].faces:
                    continue
                ax, pa = _plane(bs[i], f)
                _, pb = _plane(bs[j], f)
                if abs(pa - pb) > EPS:
                    continue
                _, ri = _rect(bs[i], f)
                _, rj = _rect(bs[j], f)
                if all(min(ri[k][1], rj[k][1]) - max(ri[k][0], rj[k][0]) > EPS for k in range(2)):
                    issues.append(f"z-fighting: {bs[i].name}#{i} и {bs[j].name}#{j}, грань {f}")
    ov = [(bs[i].name, bs[j].name, d, bs[i].a, bs[j].a) for (i, j, d) in volume_overlaps(big)]
    fl = floating(big)
    return issues, ov, fl



