def ladder(m, x, z, y0, y1, axis="x", mat="light"):
    """Вертикальная лестница шириной 4: две стойки 1x1 и перекладины через два деления. axis - вдоль какой оси ширина."""
    for y in range(y0 + 1, y1, 2):
        if axis == "x":
            m.box([x + 1, y, z], [x + 3, y + 1, z + 1], "dark")
        else:
            m.box([x, y, z + 1], [x + 1, y + 1, z + 3], "dark")
    if axis == "x":
        m.box([x, y0, z], [x + 1, y1, z + 1], mat)
        m.box([x + 3, y0, z], [x + 4, y1, z + 1], mat)
    else:
        m.box([x, y0, z], [x + 1, y1, z + 1], mat)
        m.box([x, y0, z + 3], [x + 1, y1, z + 4], mat)


